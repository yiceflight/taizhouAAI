import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import { parseHTML } from 'linkedom';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import App from '../src/App';
import { defaultSettings } from '../src/lib/workspace';
const ipc = vi.hoisted(() => ({invoke:vi.fn(),isTauri:()=>true}));
const state = vi.hoisted(() => ({workspace:{} as any}));
vi.mock('@tauri-apps/api/core',()=>ipc);
vi.mock('../src/lib/useWorkspace',()=>({useWorkspace:()=>state.workspace}));
vi.mock('../src/components/PluginUpdateAlert',()=>({PluginUpdateAlert:()=>null}));
vi.mock('../src/components/SetupPanel',()=>({SetupPanel:()=>null}));
vi.mock('../src/components/MonitoringPanel',()=>({MonitoringPanel:()=>null}));
vi.mock('../src/components/FlightReportPanel',()=>({FlightReportPanel:()=>null}));
vi.mock('../src/components/UpdateBanner',()=>({UpdateBanner:()=>null}));
vi.mock('../src/components/PluginVersionStatus',()=>({PluginVersionStatus:()=>null}));
vi.mock('../src/components/DroneStatus',()=>({DroneStatus:()=>null}));
vi.mock('../src/components/WeatherPanel',()=>({WeatherStatus:()=>null}));
vi.mock('../src/components/RuntimeLogs',()=>({RuntimeLogs:()=>null}));
let root:ReturnType<typeof createRoot>;
const oldReport={id:'old-report',title:'已删除的网页记录',source:'司空',createdAt:Date.now(),truncated:false};
const click=async(text:string)=>{await act(async()=>[...document.querySelectorAll('button')].find(b=>b.textContent===text)!.click());};
beforeEach(()=>{
  const {window}=parseHTML('<html><body><div id="root"></div></body></html>');
  window.HTMLElement.prototype.showModal=function(){this.setAttribute('open','');};
  vi.stubGlobal('window',window);vi.stubGlobal('document',window.document);vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT',true);
  root=createRoot(document.getElementById('root')!);
  state.workspace={bridge:null,readiness:null,monitor:{settings:defaultSettings,flight:{routes:[],records:[]}},error:'',acting:false,action:vi.fn(),refresh:vi.fn(async()=>{}),resetStartup:vi.fn()};
  ipc.invoke.mockReset().mockImplementation(async command=>command==='list_reports'?[oldReport]:{cleared:true});
});
afterEach(async()=>{await act(async()=>root.unmount());vi.unstubAllGlobals();});
it.each([false,true])('clears webpage rows and rejects pre-reset list receipts (pending=%s)',async(pending)=>{
  let finish!: (items:unknown[])=>void;
  if(pending)ipc.invoke.mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve;}));
  await act(async()=>root.render(<App/>));
  if(!pending)expect(document.querySelector('.capture-panel')?.textContent).toContain(oldReport.title);
  await click('设置');await click('清空数据');
  ipc.invoke.mockImplementation(async command=>command==='list_reports'?[]:{cleared:true});
  await click('确认清空数据');
  if(pending)await act(async()=>finish([oldReport]));
  expect(document.querySelector('.capture-panel')?.textContent).toContain('网页采集与历史记录（0）');
  expect(document.querySelector('.capture-panel')?.textContent).not.toContain(oldReport.title);
  expect(ipc.invoke.mock.calls.filter(call=>call[0]==='list_reports')).toHaveLength(2);
});
